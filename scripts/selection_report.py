"""Before/after of choosing the live models with winter included.

Compares, per target and city, the model deployed now (chosen on the Apr-Oct windows only)
with the winner of a comparison that also includes last winter, both scored on the same
windows. Reads a trial run written with ``--tag``::

    python -m src.run_forecasting --source live --target T --tag all_seasons   # T = AQI, PM2.5, NO2
    python scripts/selection_report.py --tag all_seasons

and writes ``reports/forecasting/live/selection_<tag>.md``. Nothing is deployed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.run_forecasting import LIVE_WINTER_ENDS  # noqa: E402

LIVE = ROOT / "reports" / "forecasting" / "live"
TARGETS = {"AQI": "aqi", "PM2.5": "pm25", "NO2": "no2"}
CITIES = ["Delhi", "Lucknow", "Ahmedabad", "Bengaluru", "Chennai", "Hyderabad"]


def deployed(slug: str) -> dict[str, str]:
    reg = json.loads((ROOT / "models" / "live" / slug / "registry.json").read_text(encoding="utf-8"))
    return {c: v["model"] for c, v in reg["cities"].items()}


def chosen(board: dict, city: str) -> str:
    mw = board["cities"][city]["multi_window"]
    return mw["best_model"] if mw["best_model_beats_baseline"] else mw["best_baseline"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="all_seasons")
    tag = ap.parse_args().tag
    winter_ends = set(LIVE_WINTER_ENDS)
    L = ["# Live models: choosing with winter included", "",
         "Each city's model is chosen by the lowest mean RMSE over its test windows and must beat the best "
         "naive forecast. Until now the live comparison used only the recent windows (spring to autumn); "
         f"this run adds last winter's four windows (ending {', '.join(LIVE_WINTER_ENDS)}). Both the model "
         "deployed now and the new winner are scored on the same windows below. RMSE is in AQI points "
         "(µg/m³ for PM2.5 and NO2). Generated by `scripts/selection_report.py`.", ""]
    totals = []
    for target, slug in TARGETS.items():
        p = LIVE / slug / tag
        if not (p / "metrics.csv").exists():
            L += [f"## {target}", "", f"_No `{tag}` run for {target} yet._", ""]
            continue
        m = pd.read_csv(p / "metrics.csv")
        board = json.loads((p / "leaderboard.json").read_text(encoding="utf-8"))
        m = m[m["error"].isna()]
        m["season"] = m["test_end"].isin(winter_ends).map({True: "winter", False: "recent"})
        dep = deployed(slug)
        recent_span = m[m["season"] == "recent"]
        span = f"{recent_span['test_start'].min()} to {recent_span['test_end'].max()}"
        rows, changes = [], 0
        for city in CITIES:
            c = m[m["city"] == city]
            if c.empty or city not in dep:
                continue
            old, new = dep[city], chosen(board, city)
            score = lambda model, season=None: c[(c["model"] == model) & ((c["season"] == season) if season else True)]["rmse"].mean()  # noqa: E731
            base = board["cities"][city]["multi_window"]["best_baseline"]
            changed = old != new
            changes += changed
            totals.append({"target": target, "city": city, "old_all": score(old), "new_all": score(new),
                           "old_winter": score(old, "winter"), "new_winter": score(new, "winter")})
            fmt = lambda v: f"{v:.1f}"  # noqa: E731
            rows.append([city, old, fmt(score(old, "recent")), fmt(score(old, "winter")), fmt(score(old)),
                         (f"**{new}**" if changed else new), fmt(score(new, "recent")), fmt(score(new, "winter")),
                         fmt(score(new)), f"{base} {score(base):.1f}"])
        L += [f"## {target}", "",
              f"Recent windows: {span}. The new choice differs in {changes} of {len(rows)} cities.", "",
              "| City | Deployed now | recent | winter | all | New choice | recent | winter | all | Best naive (all) |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        L += ["| " + " | ".join(r) + " |" for r in rows] + [""]
    if totals:
        t = pd.DataFrame(totals)
        for target, g in t.groupby("target", sort=False):
            ch_all = 100 * (g["new_all"].sum() / g["old_all"].sum() - 1)
            ch_win = 100 * (g["new_winter"].sum() / g["old_winter"].sum() - 1)
            L.append(f"- **{target}**: summed over the six cities, the new choices change the error by "
                     f"{ch_all:+.1f}% over all windows and {ch_win:+.1f}% in winter.")
        L.append("")
    out = LIVE / f"selection_{tag}.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("Wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
